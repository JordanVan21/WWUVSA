function photoId(category: GalleryCategory, year: string, file: string): string {
  const base = file
    .replace(/\.[^.]+$/, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return `${category}-${year}-${base}`;
}

function buildPhotos(sets: PhotoSet[]): GalleryPhoto[] {
  const photos: GalleryPhoto[] = [];
  const used = new Set<string>();
  for (const set of sets) {
    const featured = new Set(set.featured ?? []);
    for (const file of set.files) {
      let id = photoId(set.category, set.year, file);
      let n = 2;
      while (used.has(id)) id = `${photoId(set.category, set.year, file)}-${n++}`;
      used.add(id);
      photos.push({
        id,
        src: `/images/gallery/${set.category}/${set.year}/${encodeURIComponent(file)}`,
        category: set.category,
        year: set.year,
        type: "photo",
        alt: ALT_OVERRIDES[id] ?? set.alt,
        featured: featured.has(file) || undefined,
        order: photos.length + 1,
      });
    }
  }
  return photos;
}

